#!/usr/bin/env bash
#
# Tests for scripts/full-test.sh.          bash scripts/tests/full-test.test.sh
#
# The script under test raises a docker stack and rewrites three env files, so
# none of that is allowed to be real here. Each case copies the script into a
# throwaway git repository with an example env file and empty compose files,
# and runs it with `docker`, `npm`, `curl`, `trivy`, `openssl` and `sleep`
# replaced by stubs that write what they were asked to a log.
#
# PATH is exactly two directories — the stubs, and symlinks to an allow-list
# of real tools. /usr/bin and /bin are NOT on it: the real docker lives there,
# and on a developer's machine it is usually running the very stack this
# script must never touch. A stub that is asked for something it was not told
# to expect logs UNEXPECTED and exits 99, and the last case fails if that
# happened anywhere.
#
# PPP_FULLTEST_PORTS is pointed at a port nothing listens on, because the real
# four are taken on any machine with a stack up — which is where these tests
# are most likely to be run.
#
# PPP_TEST_SCRIPT points the suite at another copy of the script, which is how
# a deliberately broken one is shown to fail.

set -uo pipefail
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$HERE/../.." && pwd)"
SCRIPT="${PPP_TEST_SCRIPT:-$REPO_ROOT/scripts/full-test.sh}"

BASE="$(mktemp -d "${TMPDIR:-/tmp}/ppp-fulltest-test.XXXXXX")"
LISTENER=""
trap '[ -z "$LISTENER" ] || kill "$LISTENER" 2>/dev/null; rm -rf "$BASE"' EXIT

# ----- the two PATH directories ------------------------------------------------
ALLOW="bash sh env git node python3 sed awk grep sort tail head cat cp mv rm
  mkdir mktemp date diff tr cut wc printf chmod touch ls dirname basename readlink
  timeout tee cmp stat id find xargs uname true false kill"
mkdir -p "$BASE/bin" "$BASE/stubs"
for tool in $ALLOW; do
  p="$(type -P "$tool")" || { echo "cannot run: $tool is not installed" >&2; exit 1; }
  ln -s "$p" "$BASE/bin/$tool"
done

cat >"$BASE/stubs/docker" <<'STUB'
#!/usr/bin/env bash
printf 'docker %s\n' "$*" >>"$STUB/log"
S="$STUB/state"
case "${1:-}" in
  compose)
    [ "${2:-}" != "version" ] || exit 0
    verb=""
    for a in "$@"; do case "$a" in up|down|logs) verb="$a" ;; esac; done
    # What compose would see: the caller's environment, and the env file as it
    # is at this moment.
    printf 'SEEN %s DB_PASSWORD=%s PPP_TAG=%s DATA_ROOT=%s COMPOSE_PROJECT_NAME=%s last-line=%s\n' "$verb" \
      "${DB_PASSWORD-unset}" "${PPP_TAG-unset}" "${DATA_ROOT-unset}" "${COMPOSE_PROJECT_NAME-unset}" \
      "$(tail -1 .env.docker 2>/dev/null)" >>"$STUB/log"
    case "$verb" in
      up) [ ! -e "$S/up-fail" ] || exit 1; mkdir -p "$DATA_ROOT/db"; exit 0 ;;
      logs) echo "container logs"; exit 0 ;;
      down) [ ! -e "$S/term-on-down" ] || kill -TERM "$PPID"; exit 0 ;;
    esac ;;
  ps)
    case " $* " in
      *" -aq "*) cat "$S/ps-label" 2>/dev/null; exit 0 ;;
      *" -a "*) cat "$S/ps" 2>/dev/null; exit 0 ;;
    esac ;;
  network)
    case "${2:-}" in
      ls) cat "$S/networks" 2>/dev/null; exit 0 ;;
      rm) exit 0 ;;
    esac ;;
  rm) exit 0 ;;
  inspect) if [ -f "$S/owner" ]; then cat "$S/owner"; else echo "ppp-fulltest"; fi; exit 0 ;;
  run)
    case " $* " in
      *" rm -rf /o/data "*) [ ! -e "$S/rm-fail" ] || exit 1; rm -rf "${4%:/o}/data"; exit 0 ;;
      *"command -v npm"*) [ -e "$S/npm-in-image" ] && exit 0; exit 1 ;;
      *"prisma --version"*) exit 0 ;;
    esac ;;
esac
echo "unexpected: docker $*" >&2
printf 'UNEXPECTED docker %s\n' "$*" >>"$STUB/log"
exit 99
STUB

cat >"$BASE/stubs/npm" <<'STUB'
#!/usr/bin/env bash
printf 'npm %s\n' "$*" >>"$STUB/log"
S="$STUB/state"
if [ "${1:-} ${2:-}" = "run -s" ]; then
  script="${3:-}"
  case "$script" in
    typecheck|check:links|verify:models|verify:auth|verify:upload|verify:import|verify:queue|verify:frr|verify:benefits|verify:catalog|verify:api|verify:passkey|probe:security) ;;
    check:secrets)
      # The secret scanner has to see the developer's own env files.
      printf 'SCANNED %s\n' "$(tail -1 .env 2>/dev/null)" >>"$STUB/log" ;;
    env:container)
      # As scripts/use-container-env.ts does: the old .env becomes .env.backup.
      if [ -f .env ]; then cp .env .env.backup; fi
      echo "# Generated by npm run env:container" >.env ;;
    *) script="" ;;
  esac
  if [ -n "$script" ]; then
    if [ -e "$S/fail-$script" ]; then echo "this one fails"; exit 1; fi
    if [ "$(cat "$S/term-during" 2>/dev/null)" = "$script" ]; then kill -TERM "$PPID"; fi
    exit 0
  fi
fi
echo "unexpected: npm $*" >&2
printf 'UNEXPECTED npm %s\n' "$*" >>"$STUB/log"
exit 99
STUB

