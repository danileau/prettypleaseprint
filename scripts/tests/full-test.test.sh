# ----- per-case sandbox -------------------------------------------------------
T=""; N=0
new_sandbox() {
  [ -z "$T" ] || cat "$T/stub/log" >>"$BASE/all-logs" 2>/dev/null
  N=$((N + 1)); T="$BASE/s$N"
  mkdir -p "$T/repo/scripts" "$T/repo/node_modules" "$T/stub/state" "$T/home" "$T/tmp"
  : >"$T/stub/log"
  git init -q -b main "$T/repo"
  cp "$SCRIPT" "$T/repo/scripts/full-test.sh"
  ( cd "$T/repo" || exit 1
    : >docker-compose.prod.yml; : >docker-compose.build.yml; : >docker-compose.test.yml
    printf '%s\n' 'DB_PASSWORD="CHANGE-ME"' 'PPP_REGISTRY="ghcr.io/octo"' 'PPP_TAG="latest"' 'DATA_ROOT="./data"' >.env.docker.example
    printf '%s\n' '# the developer'"'"'s own' 'MINE=dev-env' >.env; chmod 600 .env
    printf '%s\n' 'MINE=dev-env-backup' >.env.backup; chmod 640 .env.backup
    printf '%s\n' 'MINE=dev-env-docker' 'PPP_TAG="v0.2.0"' >.env.docker; chmod 600 .env.docker )
  SAVED="$T/repo/.git/ppp-full-test-saved"
  LOGS="$T/out"
  STUBS="$BASE/stubs"; EXTRA=()
  ENV0="$(envsum)"
}

# Content and mode of each of the three files, or that it is not there.
envsum() {
  local f
  for f in .env .env.backup .env.docker; do
    if [ -e "$T/repo/$f" ]; then
      echo "$f $(cksum <"$T/repo/$f") $(stat -c %a "$T/repo/$f")"
    else
      echo "$f absent"
    fi
  done
}

# ft [args…] — run the script; the transcript lands in $OUT, the status in $RC.
ft() {
  ( cd "$T/repo" && timeout 60 env -i PATH="$STUBS:$BASE/bin" HOME="$T/home" TMPDIR="$T/tmp" STUB="$T/stub" \
      GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null PPP_FULLTEST_OUT="$LOGS" \
      PPP_FULLTEST_PORTS="$FREE_PORT" PPP_FULLTEST_HEALTH_TIMEOUT=1 "${EXTRA[@]}" \
      bash scripts/full-test.sh "$@" </dev/null ) >"$T/transcript" 2>&1
  RC=$?
  OUT="$(cat "$T/transcript")"
}

# ----- assertions ---------------------------------------------------------------
PASSED=0; FAILED=0; CASE=""; CASE_OK=1; DETAIL=""; OUT=""
t() { end_case; CASE="$1"; CASE_OK=1; DETAIL=""; }
end_case() {
  [ -n "$CASE" ] || return 0
  if [ "$CASE_OK" -eq 1 ]; then
    PASSED=$((PASSED + 1)); echo "ok   $CASE"
  else
    FAILED=$((FAILED + 1)); echo "FAIL $CASE"; printf '%b' "$DETAIL"
    echo "     --- last output ---"; printf '%s\n' "$OUT" | tail -12 | sed 's/^/     /'
  fi
  CASE=""
}
no() { CASE_OK=0; DETAIL+="     - $1\n"; }
rc() { [ "$RC" -eq "$1" ] || no "exit status $RC, wanted $1"; }
out() { case "$OUT" in *"$1"*) ;; *) no "output lacks: $1" ;; esac; }
no_out() { case "$OUT" in *"$1"*) no "output has: $1" ;; esac; }
logged() { grep -Eq -- "$1" "$T/stub/log" || no "log lacks: $1"; }
not_logged() { if grep -Eq -- "$1" "$T/stub/log"; then no "log has: $1"; fi; }
eq() { [ "$2" = "$3" ] || no "$1: got '$2', wanted '$3'"; }
ok() { local what=$1; shift; "$@" >/dev/null 2>&1 || no "$what"; }
nok() { local what=$1; shift; if "$@" >/dev/null 2>&1; then no "$what"; fi; }
restored() { eq "the three env files" "$(envsum)" "$ENV0"; nok "the saved copies are still there" test -e "$SAVED"; }
suites_run() { grep -E '^npm run -s (verify|probe):' "$T/stub/log" | grep -v 'verify:models' | awk '{print $4}' | tr '\n' ' '; }

