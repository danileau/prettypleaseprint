/**
 * Better Auth's half, re-based.
 *
 * The plugin describes its endpoints relative to its own mount point — it
 * emits `/sign-in/username`, because that is the path it sees. In this app
 * everything hangs off the catch-all at `/api/auth`, so each path is prefixed
 * on the way in. Its tags are prefixed too, so the console groups the sixty-odd
 * auth endpoints together instead of scattering them through the app's own.
 */
async function authPaths(): Promise<{
  paths: Record<string, unknown>;
  schemas: Record<string, unknown>;
  tags: { name: string; description: string }[];
}> {
  try {
    const spec = await auth.api.generateOpenAPISchema();
    const paths: Record<string, unknown> = {};

    for (const [path, item] of Object.entries(spec.paths ?? {})) {
      const operations = item as Record<string, { tags?: string[] } | undefined>;
      for (const operation of Object.values(operations)) {
        if (operation && Array.isArray(operation.tags)) {
          operation.tags = operation.tags.map((t) => `auth · ${t}`);
        }
      }
      paths[`/api/auth${path}`] = item;
    }

    return {
      paths,
      schemas: (spec.components?.schemas ?? {}) as Record<string, unknown>,
      tags: (spec.tags ?? []).map((t) => ({
        name: `auth · ${t.name}`,
        description: t.description,
      })),
    };
  } catch (error) {
    // A document missing its auth half is far better than no document at all —
    // and silently returning half of one is exactly the quiet failure this
    // repo tries to avoid, so it is logged and said out loud in the tag.
    console.error("[openapi] Better Auth schema unavailable", error);
    return {
      paths: {},
      schemas: {},
      tags: [
        {
          name: "auth · unavailable",
          description:
            "Better Auth's schema could not be generated for this request — " +
            "see the server log. The endpoints still exist under /api/auth.",
        },
      ],
    };
  }
}

