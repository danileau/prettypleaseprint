/**
 * The OpenAPI document, assembled at request time.
 *
 * Two halves, joined here:
 *
 *   - **The app's own endpoints**, described below. Their request shapes are
 *     not typed out twice: `z.toJSONSchema` converts the very Zod schemas the
 *     handlers validate with, so the document cannot promise a rule the server
 *     does not enforce, or miss one it does. Change `WishSchema` and the
 *     upload's documented body changes with it.
 *   - **Better Auth's endpoints**, generated by the library from its own
 *     router. It knows its own surface — sign-in, sign-up, session, passkey,
 *     reset, the admin plugin — and that surface moves when a plugin is added
 *     or a version is bumped. Copying it by hand would be a second source of
 *     truth with a shorter shelf life than the first.
 *
 *     This is called **in process**, never over HTTP. The `openAPI()` plugin
 *     that provides it also mounts `/api/auth/open-api/generate-schema`, and
 *     that endpoint answers 200 to anybody with no session — it would hand a
 *     stranger the list of which auth plugins this deployment runs and every
 *     path they expose, while the app's own document next door sits behind a
 *     session. Middleware answers 404 for it; see `src/middleware.ts`.
 *     (Importing the generator function directly would have avoided mounting
 *     anything, but Better Auth 1.7.1 declares that export in its types and
 *     does not actually re-export it at runtime.)
 *
 * Assembled per request rather than at build time because the server URL and
 * the session cookie's name both come from the deployment's environment, and
 * `next build` runs without it.
 */

/** OpenAPI 3.1 is a JSON Schema 2020-12 dialect, so this is a lift, not a translation. */
function jsonSchema(schema: z.ZodType): Record<string, unknown> {
  const converted = z.toJSONSchema(schema, {
    io: "input",
    unrepresentable: "any",
  }) as Record<string, unknown>;
  // `$schema` is legal in a JSON Schema document and noise in a components
  // entry — every tool already knows the dialect from `openapi: "3.1.0"`.
  delete converted.$schema;
  return converted;
}

